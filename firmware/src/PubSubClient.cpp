boolean PubSubClient::publish(const char* topic, const uint8_t* payload, unsigned int plength, boolean retained) {
    if (connected()) {
        if (this->bufferSize < MQTT_MAX_HEADER_SIZE + 2+strnlen(topic, this->bufferSize) + plength) {
            // Payload too large for standard publish buffer
            return false;
        }
        // Leave room in the buffer for header and variable length field
        uint16_t length = MQTT_MAX_HEADER_SIZE;
        length = writeString(topic,this->buffer,length);
        uint16_t i;
        for (i=0;i<plength;i++) {
            this->buffer[length++] = payload[i];
        }
        uint8_t header = MQTTPUBLISH;
        if (retained) {
            header |= 1;
        }
        return write(header,this->buffer,length-MQTT_MAX_HEADER_SIZE);
    }
    return false;
}

boolean PubSubClient::beginPublish(const char* topic, uint16_t plength, boolean retained) {
    if (connected()) {
        // Send the header and variable length field
        uint16_t length = MQTT_MAX_HEADER_SIZE;
        length = writeString(topic,this->buffer,length);
        uint8_t header = MQTTPUBLISH;
        if (retained) {
            header |= 1;
        }
        size_t hlen = length-MQTT_MAX_HEADER_SIZE;
        size_t pos = (MQTT_MAX_HEADER_SIZE-1);
        size_t remLen = hlen + plength;
        do {
            uint8_t digit = remLen & 127;
            remLen >>= 7;
            if (remLen > 0) {
                digit |= 128;
            }
            this->buffer[pos--] = digit;
        } while(remLen > 0);
        this->buffer[pos] = header;
        _client->write(this->buffer+pos, (MQTT_MAX_HEADER_SIZE-pos)+hlen);
        return true;
    }
    return false;
}

int PubSubClient::endPublish() {
    return 1;
}

